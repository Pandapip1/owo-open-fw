/// One CCC state block per notifying characteristic.
macro_rules! ccc_data {
    ($name:ident) => {
        static $name: Racy<bt_gatt_ccc_managed_user_data> = Racy::new({
            // SAFETY: an all-zero CCC block is exactly BT_GATT_CCC_INITIALIZER with a
            // NULL write/match callback, which is what BT_GATT_CCC() produces.
            let mut d: bt_gatt_ccc_managed_user_data = unsafe { core::mem::zeroed() };
            d.cfg_changed = Some(ccc_changed);
            d
        });
    };
}
