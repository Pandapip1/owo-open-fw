unsafe extern "C" fn connected(conn: *mut bt_conn, err: u8) {
    if err != 0 {
        warn!("connect failed (0x{:02x})", err);
        return;
    }
    info!("connected; requiring authenticated pairing");
    let e = bt_conn_set_security(conn, BT_SECURITY_L3 as _);
    if e != 0 {
        warn!("set_security {}", e);
    }
}

unsafe extern "C" fn disconnected(_conn: *mut bt_conn, reason: u8) {
    info!("disconnected (0x{:02x})", reason);
    if crate::resetting() {
        return;
    }
    // Never leave anything playing without a controller attached.
    crate::stop_all();
    if let Err(e) = adv_start() {
        warn!("adv restart failed ({})", e);
    }
}

/// Stop Bluetooth before an intentional reset. Called from the pump, never a
/// GATT callback. A failure is logged and the still-running watchdog bounds a
/// controller/transport teardown that does not return.
pub(crate) fn shutdown() {
    // SAFETY: the pump calls this only after synchronous `bt_enable` succeeded.
    let e = unsafe { bt_disable() };
    if e != 0 {
        warn!("Bluetooth shutdown failed ({})", e);
    }
}

fn adv_start() -> Result<(), c_int> {
    let ad = [bt_data {
        type_: BT_DATA_FLAGS,
        data_len: 1,
        data: &(BT_LE_AD_GENERAL | BT_LE_AD_NO_BREDR) as *const u8,
    }];
    // SAFETY: bt_get_name returns a NUL-terminated string that lives as long as the stack.
    let (name, name_len) = unsafe {
        let p = bt_get_name();
        let mut n = 0usize;
        while *p.add(n) != 0 {
            n += 1;
        }
        (p.cast::<u8>(), n)
    };
    let sd = [bt_data { type_: BT_DATA_NAME_COMPLETE, data_len: name_len as u8, data: name }];

    // BT_GAP_MS_TO_ADV_INTERVAL(ms) = ms * 1000 / 625
    let min = (zephyr::kconfig::CONFIG_OWO_ADV_INTERVAL_MS as u32) * 1000 / 625;
    let param = bt_le_adv_param {
        id: 0,
        sid: 0,
        secondary_max_skip: 0,
        options: BT_LE_ADV_OPT_CONN,
        interval_min: min,
        interval_max: min + 8,
        peer: ptr::null(),
        ..Default::default()
    };
    // SAFETY: all pointers are valid for the call; Zephyr copies the data.
    let r = unsafe { bt_le_adv_start(&param, ad.as_ptr(), ad.len(), sd.as_ptr(), sd.len()) };
    if r == 0 {
        Ok(())
    } else {
        Err(r)
    }
}

/// Register services and callbacks, enable the stack and start advertising.
pub(crate) fn start() -> Result<(), c_int> {
    // SAFETY: called once, from the main thread, before the stack is enabled; the
    // statics are never moved and live for the whole program.
    unsafe {
        *AUTH_CB.get() = Some(bt_conn_auth_cb {
            app_passkey: Some(app_passkey),
            cancel: Some(pairing_cancel),
            ..Default::default()
        });
        *CONN_CB.get() = Some(bt_conn_cb {
            connected: Some(connected),
            disconnected: Some(disconnected),
            ..Default::default()
        });
        (*SVC1_ATTRS.get()).write(svc1_attrs());
        (*SVC2_ATTRS.get()).write(svc2_attrs());
        (*SVC3_ATTRS.get()).write(svc3_attrs());
        *SVC1.get() = Some(bt_gatt_service {
            attrs: SVC1_ATTRS.get().cast(),
            attr_count: SVC1_LEN,
            ..Default::default()
        });
        *SVC2.get() = Some(bt_gatt_service {
            attrs: SVC2_ATTRS.get().cast(),
            attr_count: SVC2_LEN,
            ..Default::default()
        });

        *SVC3.get() = Some(bt_gatt_service {
            attrs: SVC3_ATTRS.get().cast(),
            attr_count: SVC3_LEN,
            ..Default::default()
        });

        let e = bt_conn_auth_cb_register((*AUTH_CB.get()).as_ref().unwrap());
        if e != 0 {
            return Err(e);
        }
        let e = bt_conn_cb_register((*CONN_CB.get()).as_mut().unwrap());
        if e != 0 {
            return Err(e);
        }
        for svc in [SVC1.get(), SVC2.get(), SVC3.get()] {
            let e = bt_gatt_service_register((*svc).as_mut().unwrap());
            if e != 0 {
                return Err(e);
            }
        }
        let e = bt_enable(None);
        if e != 0 {
            return Err(e);
        }
    }
    adv_start()
}
