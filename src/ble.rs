fn primary(svc: &'static bt_uuid_128) -> bt_gatt_attr {
    attr(
        &U_PRIMARY.uuid,
        Some(bt_gatt_attr_read_service),
        None,
        &svc.uuid as *const bt_uuid as *mut c_void,
        PERM_READ,
    )
}

fn decl(c: &'static Racy<bt_gatt_chrc>) -> bt_gatt_attr {
    attr(&U_CHRC.uuid, Some(bt_gatt_attr_read_chrc), None, c.get().cast(), PERM_READ)
}

/// Value attribute; access is mediated by `read_cb` / `write_cb` (or only one of them).
fn value(uuid: &'static bt_uuid_128, id: Id, readable: bool, writable: bool) -> bt_gatt_attr {
    attr(
        u(uuid),
        if readable { Some(read_cb) } else { None },
        if writable { Some(write_cb) } else { None },
        id as usize as *mut c_void,
        (if readable { PERM_READ_AUTHEN } else { 0 }) | (if writable { PERM_WRITE_AUTHEN } else { 0 }),
    )
}

fn ccc(d: &'static Racy<bt_gatt_ccc_managed_user_data>) -> bt_gatt_attr {
    attr(
        &U_CCC.uuid,
        Some(bt_gatt_attr_read_ccc),
        Some(bt_gatt_attr_write_ccc),
        d.get().cast(),
        PERM_READ_AUTHEN | PERM_WRITE_AUTHEN,
    )
}

fn cud(s: &'static [u8]) -> bt_gatt_attr {
    attr(&U_CUD.uuid, Some(bt_gatt_attr_read_cud), None, s.as_ptr() as *mut c_void, PERM_READ)
}

