// ---- characteristic identity ----------------------------------------------------
// Carried in `attr.user_data` as a small integer so the callbacks need no pointers
// to mutable state.
#[derive(Clone, Copy, PartialEq, Eq)]
#[repr(usize)]
enum Id {
    Widths = 1,
    Run,
    Frame,
    Power,
    Status,
    Extra1,
    FwPkg,
    SerProg,
    Test,
    Extra2,
    OtaControl,
}

impl Id {
    fn from_attr(a: *const bt_gatt_attr) -> Option<Id> {
        // SAFETY: Zephyr hands back one of our own attributes.
        let v = unsafe { (*a).user_data } as usize;
        Some(match v {
            1 => Id::Widths,
            2 => Id::Run,
            3 => Id::Frame,
            4 => Id::Power,
            5 => Id::Status,
            6 => Id::Extra1,
            7 => Id::FwPkg,
            8 => Id::SerProg,
            9 => Id::Test,
            10 => Id::Extra2,
            11 => Id::OtaControl,
            _ => return None,
        })
    }
}

/// Channel status: bit set = channel open (no skin contact) [from the app decode:
/// 8 bits in byte 9, 2 bits in byte 8]. There is no contact sensing in this build,
/// so report EVERY channel as open rather than claim good contact.
const STATUS: [u8; 10] = [0, 0, 0, 0, 0, 0, 0, 0, 0x03, 0xFF];

// ---- callbacks -------------------------------------------------------------------

unsafe fn read_value(
    conn: *mut bt_conn,
    attr: *const bt_gatt_attr,
    buf: *mut c_void,
    len: u16,
    off: u16,
    v: &[u8],
) -> isize {
    bt_gatt_attr_read(conn, attr, buf, len, off, v.as_ptr().cast(), v.len() as u16)
}

unsafe extern "C" fn read_cb(
    conn: *mut bt_conn,
    attr: *const bt_gatt_attr,
    buf: *mut c_void,
    len: u16,
    off: u16,
) -> isize {
    let Some(id) = Id::from_attr(attr) else {
        return -ATT_UNLIKELY;
    };
    // Copy out under the lock, answer after releasing it.
    let mut tmp = [0u8; 20];
    let n = {
        let s = STATE.lock().unwrap();
        let v: &[u8] = match id {
            Id::Widths => &s.v_widths,
            Id::Run => core::slice::from_ref(&s.v_run),
            Id::Frame => &s.v_frame,
            Id::Power => &s.v_power,
            Id::Status => &STATUS,
            Id::Extra1 => &s.v_extra1,
            Id::Test => &s.v_test,
            Id::Extra2 => &s.v_extra2,
            Id::FwPkg | Id::SerProg | Id::OtaControl => return -ATT_UNLIKELY,
        };
        tmp[..v.len()].copy_from_slice(v);
        v.len()
    };
    read_value(conn, attr, buf, len, off, &tmp[..n])
}

fn map_err(e: Error) -> isize {
    match e {
        Error::Len => -ATT_INVALID_ATTRIBUTE_LEN,
        Error::Csum | Error::Range => -ATT_VALUE_NOT_ALLOWED,
    }
}

unsafe extern "C" fn write_cb(
    _conn: *mut bt_conn,
    attr: *const bt_gatt_attr,
    buf: *const c_void,
    len: u16,
    off: u16,
    _flags: u8,
) -> isize {
    let Some(id) = Id::from_attr(attr) else {
        return -ATT_UNLIKELY;
    };
    if off != 0 {
        return -ATT_INVALID_OFFSET;
    }
    // SAFETY: Zephyr guarantees `buf` is valid for `len` bytes.
    let data = core::slice::from_raw_parts(buf.cast::<u8>(), len as usize);

    let res: Result<(), Error> = match id {
        Id::Widths => crate::on_widths(data).map(|_| store(|s| copy(&mut s.v_widths, data))),
        Id::Power => crate::on_power(data).map(|_| store(|s| copy(&mut s.v_power, data))),
        Id::Extra1 => crate::on_config(data).map(|_| store(|s| copy(&mut s.v_extra1, data))),
        Id::Frame => {
            let r = crate::on_frame(data);
            match r {
                Ok(()) => store(|s| copy(&mut s.v_frame, data)),
                // Checksum failure is also reported on "Start / Stop" (fw @0x263AC).
                Err(Error::Csum) => notify_run(proto::NOTIFY_BAD_CHECKSUM),
                Err(_) => {}
            }
            r
        }
        Id::Run => {
            if len != 1 {
                return -ATT_INVALID_ATTRIBUTE_LEN;
            }
            match crate::on_run(data[0]) {
                Ok(()) => {
                    store(|s| s.v_run = data[0]);
                    Ok(())
                }
                Err(()) => return -ATT_VALUE_NOT_ALLOWED,
            }
        }
        // "Firmware Package": no behaviour for it was found in the stock image;
        // accepted and discarded.
        Id::FwPkg => Ok(()),
        // "Test": untraced in the stock image; keep the last frame-sized write.
        Id::Test => {
            if data.len() == proto::FRAME_LEN {
                store(|s| copy(&mut s.v_test, data));
            }
            Ok(())
        }
        // "Serial number programming" is a factory provisioning gate and has no
        // place in this build.
        Id::SerProg => return -ATT_WRITE_NOT_PERMITTED,
        // Silicon Labs OTA control: 0x00 = start the upgrade (reboot into the bootloader, which
        // then does the whole transfer). Other opcodes belong to the bootloader's own service.
        Id::OtaControl => {
            if len != 1 {
                return -ATT_INVALID_ATTRIBUTE_LEN;
            }
            if data[0] == 0 {
                crate::on_ota_start();
            }
            Ok(())
        }
        Id::Status | Id::Extra2 => return -ATT_WRITE_NOT_PERMITTED,
    };
    match res {
        Ok(()) => len as isize,
        Err(e) => map_err(e),
    }
}

fn store(f: impl FnOnce(&mut crate::State)) {
    f(&mut STATE.lock().unwrap());
}

fn copy<const N: usize>(dst: &mut [u8; N], src: &[u8]) {
    dst.copy_from_slice(src);
}

unsafe extern "C" fn ccc_changed(_attr: *const bt_gatt_attr, value: u16) {
    log::debug!("CCC {:04x}", value);
}

// ---- attribute table ---------------------------------------------------------------

type ReadFn = bt_gatt_attr_read_func_t;
type WriteFn = bt_gatt_attr_write_func_t;

/// `perm` is a bitfield in this Zephyr version (`perm:15` + `_auto_assigned_handle:1`),
/// so attributes cannot be built in a `const` initialiser; the tables are filled in
/// `start()`.
fn attr(
    uuid: *const bt_uuid,
    read: ReadFn,
    write: WriteFn,
    user_data: *mut c_void,
    perm: u16,
) -> bt_gatt_attr {
    let mut a = bt_gatt_attr { uuid, read, write, user_data, handle: 0, ..Default::default() };
    a.set_perm(perm);
    a
}

const fn u(x: &'static bt_uuid_128) -> *const bt_uuid {
    &x.uuid
}

/// Characteristic declaration payloads (uuid + properties; the value handle is
/// derived by Zephyr from the attribute that follows).
macro_rules! chrc_decl {
    ($name:ident, $uuid:expr, $props:expr) => {
        static $name: Racy<bt_gatt_chrc> =
            Racy::new(bt_gatt_chrc { uuid: u(&$uuid), value_handle: 0, properties: $props });
    };
}
