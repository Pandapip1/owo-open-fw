/// Interior-mutable static for data Zephyr mutates through raw pointers.
struct Racy<T>(UnsafeCell<T>);
// SAFETY: Zephyr serialises access to registered GATT attributes internally; this
// firmware never touches them after registration.
unsafe impl<T> Sync for Racy<T> {}
impl<T> Racy<T> {
    const fn new(v: T) -> Self {
        Racy(UnsafeCell::new(v))
    }
    const fn get(&self) -> *mut T {
        self.0.get()
    }
}

