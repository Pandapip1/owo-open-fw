//! BLE: the suit's GATT database, rebuilt from the 7.9.07 attribute table
//! (fw @0x16280), plus pairing, advertising and connection handling.
//!
//! Zephyr's GATT table macros (`BT_GATT_SERVICE_DEFINE`) are C preprocessor
//! constructs, so the table is built here as `bt_gatt_attr` arrays and
//! registered at run time (`CONFIG_BT_GATT_DYNAMIC_DB`). Attribute handles are
//! assigned by Zephyr and will not match the stock ones (24, 27, 31, ...); both
//! official apps look characteristics up by UUID, so that does not matter for them.
//!
//! Device Information (manufacturer "OWO") and Battery come from Zephyr's own
//! `CONFIG_BT_DIS` / `CONFIG_BT_BAS`.
//!
//! Every constant below that is not in the generated bindings (they only expose
//! `bt_*` functions and `CONFIG_BT_*`) is copied from the Zephyr headers; the
//! header is named next to each.

