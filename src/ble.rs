chrc_decl!(C_RUN, U_RUN, CHRC_READ | CHRC_WRITE | CHRC_NOTIFY);
chrc_decl!(C_FRAME, U_FRAME, CHRC_READ | CHRC_WRITE);
chrc_decl!(C_POWER, U_POWER, CHRC_READ | CHRC_WRITE | CHRC_NOTIFY);
chrc_decl!(C_STATUS, U_STATUS, CHRC_READ | CHRC_NOTIFY);
chrc_decl!(C_EXTRA1, U_EXTRA1, CHRC_READ | CHRC_WRITE);
chrc_decl!(C_FWPKG, U_FWPKG, CHRC_WRITE);
chrc_decl!(C_SERPROG, U_SERPROG, CHRC_WRITE);
chrc_decl!(C_TEST, U_TEST, CHRC_READ | CHRC_WRITE | CHRC_NOTIFY);
chrc_decl!(C_EXTRA2, U_EXTRA2, CHRC_READ | CHRC_NOTIFY);
