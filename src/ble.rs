// ---- notifications ------------------------------------------------------------------

fn notify(attrs: *const bt_gatt_attr, uuid: &'static bt_uuid_128, data: &[u8]) {
    let mut p = bt_gatt_notify_params {
        uuid: &uuid.uuid,
        attr: attrs,
        data: data.as_ptr().cast(),
        len: data.len() as u16,
        ..Default::default()
    };
    // SAFETY: `attrs` is a registered attribute array and `data` outlives the call;
    // a NULL connection notifies every subscribed peer.
    let r = unsafe { bt_gatt_notify_cb(ptr::null_mut(), &mut p) };
    // -ENOTCONN / not subscribed is normal.
    if r != 0 {
        log::debug!("notify {}", r);
    }
}

pub(crate) fn notify_run(v: u8) {
    store(|s| s.v_run = v);
    notify(SVC1_ATTRS.get().cast(), &U_RUN, &[v]);
}

pub(crate) fn notify_extra2(rec: &[u8; 10]) {
    store(|s| s.v_extra2 = *rec);
    notify(SVC2_ATTRS.get().cast(), &U_EXTRA2, rec);
}

