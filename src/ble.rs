// ---- UUIDs (fw @0x161D0 table) -----------------------------------------------

/// BT_UUID_128_ENCODE(w32, w1, w2, w3, w48): little-endian byte list
/// w48(6) w3(2) w2(2) w1(2) w32(4).
const fn uuid128(w32: u32, w1: u16, w2: u16, w3: u16, w48: u64) -> bt_uuid_128 {
    let mut v = [0u8; 16];
    let mut i = 0;
    while i < 6 {
        v[i] = (w48 >> (8 * i)) as u8;
        i += 1;
    }
    v[6] = w3 as u8;
    v[7] = (w3 >> 8) as u8;
    v[8] = w2 as u8;
    v[9] = (w2 >> 8) as u8;
    v[10] = w1 as u8;
    v[11] = (w1 >> 8) as u8;
    let mut j = 0;
    while j < 4 {
        v[12 + j] = (w32 >> (8 * j)) as u8;
        j += 1;
    }
    bt_uuid_128 { uuid: bt_uuid { type_: BT_UUID_TYPE_128 }, val: v }
}

/// Two UUID bases exist: ...-C6A9-11E4-8731-1681E6B88EC1 and ...-C717-...
const fn ua(w32: u32) -> bt_uuid_128 {
    uuid128(w32, 0xC6A9, 0x11E4, 0x8731, 0x1681E6B88EC1)
}
const fn ub(w32: u32) -> bt_uuid_128 {
    uuid128(w32, 0xC717, 0x11E4, 0x8731, 0x1681E6B88EC1)
}

